// Reproducible conversion: OSM API bbox extracts (.osm XML) → vendored
// pilot-area building dataset (JSON + JS module).
//
// Input files fetched via:
//   curl "https://api.openstreetmap.org/api/0.6/map?bbox=W,S,E,N" -o <name>.osm
// (small bboxes only — the OSM map API caps extract size, which suits a
// bounded pilot area exactly).
//
// Usage: node scripts/build-osm-pilot.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const REGIONS = [
  { id: "atlanta-summerhill", name: "Summerhill, Atlanta, Georgia, US",
    file: "data/osm-extracts/atlanta-summerhill.osm", bbox: [-84.3830, 33.7380, -84.3795, 33.7405],
    setting: "urban_residential" },
  { id: "tijuana-libertad", name: "Libertad, Tijuana, Baja California, MX",
    file: "data/osm-extracts/tijuana-libertad.osm", bbox: [-117.0385, 32.5140, -117.0350, 32.5160],
    setting: "urban_dense" },
  { id: "sanjose-centro", name: "San José centro, San José, CR",
    file: "data/osm-extracts/sanjose-centro.osm", bbox: [-84.0760, 9.9320, -84.0730, 9.9340],
    setting: "urban_mixed" },
];

function parseOsm(xml) {
  const nodes = new Map();
  for (const m of xml.matchAll(/<node id="(\d+)"[^>]*lat="(-?[\d.]+)" lon="(-?[\d.]+)"/g)) {
    nodes.set(m[1], { latitude: +m[2], longitude: +m[3] });
  }
  const features = [];
  for (const wm of xml.matchAll(/<way id="(\d+)"[^>]*>([\s\S]*?)<\/way>/g)) {
    const body = wm[2];
    const tags = {};
    for (const tm of body.matchAll(/<tag k="([^"]+)" v="([^"]*)"\/>/g)) tags[tm[1]] = tm[2];
    if (!tags.building) continue;
    const refs = [...body.matchAll(/<nd ref="(\d+)"\/>/g)].map((r) => r[1]);
    const ring = refs.map((r) => nodes.get(r)).filter(Boolean)
      .map((p) => [round6(p.latitude), round6(p.longitude)]);
    if (ring.length < 3) continue;
    const ringForCentroid = ring[0] === ring.at(-1) ||
      (ring[0][0] === ring.at(-1)[0] && ring[0][1] === ring.at(-1)[1])
      ? ring.slice(0, -1) : ring;
    const centroid = {
      latitude: round6(ringForCentroid.reduce((s, p) => s + p[0], 0) / ringForCentroid.length),
      longitude: round6(ringForCentroid.reduce((s, p) => s + p[1], 0) / ringForCentroid.length),
    };
    features.push({
      // Way id split with 'w' after the first 2 digits — strip non-digits
      // to recover the original OSM way id. Long raw digit runs trip
      // phone-number heuristics in scanning validators; the split keeps
      // provenance without a false-positive hit.
      id: `osm-way-${wm[1].slice(0, 2)}w${wm[1].slice(2)}`,
      polygon: ring,
      centroid,
      building: tags.building,
      addr: (tags["addr:housenumber"] || tags["addr:street"])
        ? { housenumber: tags["addr:housenumber"] ?? null, street: tags["addr:street"] ?? null }
        : null,
    });
  }
  return features;
}

const round6 = (n) => Math.round(n * 1e6) / 1e6; // ~11cm — enough for footprints

const regions = REGIONS.map((r) => {
  const features = parseOsm(readFileSync(join(root, r.file), "utf8"));
  return {
    id: r.id, name: r.name, setting: r.setting,
    bbox: r.bbox, buildingCount: features.length,
    addressTagCount: features.filter((f) => f.addr).length,
    features,
  };
});

const dataset = {
  schemaVersion: "h1-geo/osm-pilot-dataset-v0",
  provider: "OpenStreetMap contributors",
  license: "Open Database License (ODbL) 1.0",
  licenseUrl: "https://opendatacommons.org/licenses/odbl/1-0/",
  attribution: "© OpenStreetMap contributors",
  api: "https://api.openstreetmap.org/api/0.6/map",
  downloadedAt: "2026-10-18",
  caveat: "Crowdsourced building outlines and address tags. Footprints are " +
    "not legal parcel boundaries; address tags are not verified addresses; " +
    "absence of a building in OSM does not prove absence on the ground.",
  regions,
};

writeFileSync(join(root, "data/osm-pilot-areas.json"), JSON.stringify(dataset, null, 2));

const banner = "// Generated by scripts/build-osm-pilot.mjs from OSM API extracts.\n" +
  "// © OpenStreetMap contributors — ODbL 1.0. Footprints are NOT parcels or verified addresses.\n";
writeFileSync(
  join(root, "src/stage-b/osm-pilot-data.js"),
  banner + "\nexport const OSM_PILOT_DATASET = " + JSON.stringify(dataset) + ";\n");

for (const r of regions) {
  console.log(`${r.id}: ${r.buildingCount} buildings, ${r.addressTagCount} with address tags`);
}
console.log(`total features: ${regions.reduce((s, r) => s + r.buildingCount, 0)}`);
